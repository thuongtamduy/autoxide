/// A post or page — its working draft.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub(crate) struct EntryResponse {
    id: Uuid,
    kind: Kind,
    /// The custom content type of an entry of kind `custom` (`GET /types`); `null` otherwise.
    type_id: Option<Uuid>,
    /// Language, a BCP 47 code.
    #[schema(example = "vi")]
    locale: String,
    /// Shared by the translations of the same entry.
    translation_group_id: Uuid,
    /// The parent page (pages only); `null` at the root.
    parent_id: Option<Uuid>,
    status: Status,
    /// `true` when the draft has changes not yet published.
    has_unpublished_changes: bool,
    #[schema(example = "Đường đến Đà Lạt")]
    title: String,
    /// Last part of the address.
    #[schema(example = "duong-den-da-lat")]
    slug: String,
    /// Short summary.
    excerpt: String,
    /// The body, a ProseMirror / Tiptap JSON document.
    #[schema(value_type = BodyNode)]
    body: Value,
    /// Version of the list of allowed body nodes (currently 1).
    body_schema_version: i32,
    /// Words in the body (for Vietnamese: syllables).
    word_count: i32,
    reading_time_minutes: i32,
    /// Main image (a media item id).
    featured_media_id: Option<Uuid>,
    featured_media_alt: String,
    meta_title: String,
    meta_description: String,
    /// Image for social sharing (a media item id).
    og_media_id: Option<Uuid>,
    canonical_url: String,
    noindex: bool,
    /// The content was generated by AI (set by the writer; set by the server when it translated
    /// the entry, and always when the writer has only `content.write_own`). Shown to readers by
    /// the public endpoints.
    ai_generated: bool,
    /// A person wrote or edited the content from AI suggestions (e.g. applied
    /// `seo-suggestions`). Public endpoints return it so the interface labels the content
    /// (Vietnam's Law on Artificial Intelligence 134/2025/QH15, from 2026-03-01).
    ai_assisted: bool,
    /// When the writer asked for a review (`POST /entries/{id}/request-review`); `null`: no
    /// review pending. Cleared when the entry is published.
    review_requested_at: Option<Timestamp>,
    /// Who asked for the review.
    review_requested_by: Option<Uuid>,
    /// For a translation made by the server's AI: the revision of the source it was translated
    /// from; `null` otherwise.
    translated_from_revision_id: Option<Uuid>,
    /// `true` when the source changed after this AI translation was made: translate it again
    /// (`POST /entries/{source}/translate`) or update it by hand.
    translation_outdated: bool,
    created_by: Option<Uuid>,
    /// How the entry was created: `session` (a person signed in) or `api_key` (a machine or an
    /// AI agent).
    #[schema(example = "api_key")]
    created_via: String,
    created_at: Timestamp,
    updated_at: Timestamp,
    /// Categories and tags, in order (the first category is the main one). Set with
    /// `PUT /api/v1/content/entries/{id}/terms`; takes effect at once.
    term_ids: Vec<Uuid>,
    /// Authors, in order (the first is the main one). Set with
    /// `PUT /api/v1/content/entries/{id}/authors`; takes effect at once.
    author_ids: Vec<Uuid>,
    /// When the public version was last published; `null` while the entry is not public.
    published_at: Option<Timestamp>,
    /// Address of the public version, e.g. `/blog/duong-den-da-lat` or `/about/team` (a page
    /// carries the path of its parents); `null` while the entry is not public. It does not hold
    /// the language: the website decides how `locale` shows in its addresses.
    #[schema(example = "/blog/duong-den-da-lat")]
    path: Option<String>,
    /// The entry's `ETag` (as `GET /entries/{id}` sends it): send it in `If-Match` to change the
    /// entry straight from a list.
    #[schema(example = "\"1731628800000000\"")]
    version: String,
    /// The tenant's internal tags (`PUT /api/v1/kernel/records/content.entry/{id}/tags`).
    tags: Vec<autoxide_kernel::tags::TagRef>,
    /// Values of the tenant's custom fields, by key.
    #[schema(value_type = Object)]
    custom_fields: serde_json::Map<String, Value>,
}

/// Mục như API trả, kèm term và tác giả (đọc chung một lần cho mọi mục), và bản dịch AI nào đã
/// cũ (bản gốc sửa sau revision đã dịch).
pub(crate) async fn describe(
    service: &ContentService,
    tenant: &TenantContext,
    entries: Vec<Entry>,
) -> Result<Vec<EntryResponse>, Error> {
    let ids: Vec<Uuid> = entries.iter().map(|entry| entry.id).collect();
    let mut terms = service.term_ids(tenant, &ids).await?;
    let mut authors = service.author_ids(tenant, &ids).await?;
    let outdated = service.outdated_translations(tenant, &entries).await?;
    let mut live = service.published_paths(tenant, &ids).await?;
    // Nhãn nội bộ (bước 51 P20): một câu cho cả trang.
    let keys: Vec<String> = ids.iter().map(ToString::to_string).collect();
    let mut tags =
        autoxide_kernel::tags::TagIndex.of_records(tenant, crate::resource::ENTRY, &keys).await?;
    Ok(entries
        .into_iter()
        .map(|entry| {
            let (term_ids, author_ids) = (
                terms.remove(&entry.id).unwrap_or_default(),
                authors.remove(&entry.id).unwrap_or_default(),
            );
            let stale = outdated.contains(&entry.id);
            let public = live.remove(&entry.id);
            let entry_tags = tags.remove(&entry.id.to_string()).unwrap_or_default();
            let mut response = entry_response(entry, term_ids, author_ids, stale);
            response.tags = entry_tags;
            if let Some((path, published_at)) = public {
                response.path = Some(path);
                response.published_at = Some(published_at);
            }
            response
        })
        .collect())
}

/// API trả mục như thế nào.
fn entry_response(
    entry: Entry,
    term_ids: Vec<Uuid>,
    author_ids: Vec<Uuid>,
    translation_outdated: bool,
) -> EntryResponse {
    let custom_fields = crate::entries::stored_custom(&entry);
    EntryResponse {
        translation_outdated,
        translated_from_revision_id: entry.translated_from_revision_id,
        term_ids,
        author_ids,
        kind: Kind::parse(&entry.kind).unwrap_or(Kind::Post),
        type_id: entry.type_id,
        status: Status::of(&entry),
        body: serde_json::from_str(&entry.body).unwrap_or(Value::Null),
        id: entry.id,
        locale: entry.locale,
        translation_group_id: entry.translation_group_id,
        parent_id: entry.parent_id,
        has_unpublished_changes: entry.has_unpublished_changes,
        title: entry.title,
        slug: entry.slug,
        excerpt: entry.excerpt,
        body_schema_version: entry.body_schema_version,
        word_count: entry.word_count,
        reading_time_minutes: entry.reading_time_minutes,
        featured_media_id: entry.featured_media_id,
        featured_media_alt: entry.featured_media_alt,
        meta_title: entry.meta_title,
        meta_description: entry.meta_description,
        og_media_id: entry.og_media_id,
        canonical_url: entry.canonical_url,
        noindex: entry.noindex,
        ai_generated: entry.ai_generated,
        ai_assisted: entry.ai_assisted,
        review_requested_at: entry.review_requested_at,
        review_requested_by: entry.review_requested_by,
        created_by: entry.created_by,
        created_via: if entry.created_by_api_key_id.is_some() { "api_key" } else { "session" }
            .to_owned(),
        version: autoxide_kernel::version::etag(entry.updated_at),
        published_at: None,
        path: None,
        tags: Vec::new(),
        custom_fields: custom_fields.unwrap_or_default(),
        created_at: entry.created_at,
        updated_at: entry.updated_at,
    }
}

/// Một mục kèm `ETag`.
pub(crate) async fn tagged(
    service: &ContentService,
    tenant: &TenantContext,
    entry: Entry,
) -> Result<Tagged<EntryResponse>, Error> {
    let version = entry.updated_at;
    let data = describe(service, tenant, vec![entry])
        .await?
        .into_iter()
        .next()
        .ok_or_else(|| Error::internal("describe returned nothing"))?;
    Ok(Tagged { version, data })
}

/// Filters and order of the entry list.
#[derive(Debug, Clone, Default, Deserialize, IntoParams)]
#[into_params(parameter_in = Query)]
pub(crate) struct EntriesQuery {
    /// `post`, `page` or `custom`.
    #[param(value_type = Option<Kind>, inline)]
    pub kind: Option<String>,
    /// Only entries of this custom content type.
    pub type_id: Option<Uuid>,
    /// Only this language.
    #[param(example = "vi")]
    pub locale: Option<String>,
    /// `draft`, `published` or `archived`.
    #[param(value_type = Option<Status>, inline)]
    pub status: Option<String>,
    /// Only entries directly under this page: an entry id, or `root` (every post and the
    /// top-level pages).
    pub parent_id: Option<String>,
    /// Only entries whose title, summary or body contains this text, ignoring case and accents.
    pub q: Option<String>,
    /// Only entries with this category or tag.
    pub term_id: Option<Uuid>,
    /// Only entries by this author.
    pub author_id: Option<Uuid>,
    /// Only the translations of one entry (its `translation_group_id`).
    pub translation_group_id: Option<Uuid>,
    /// `created_at` (the default) or `updated_at`; newest first unless `order` says otherwise.
    #[param(value_type = Option<EntrySort>, inline)]
    pub sort: Option<String>,
    /// `true`: only entries waiting for a review (`review_requested_at` set); `false`: only the
    /// others.
    pub review_requested: Option<bool>,
    /// `true`: only entries with a scheduled publish or unpublish waiting; `false`: only the
    /// others.
    pub scheduled: Option<bool>,
    /// Only entries created by this user: a user id, or `me` for the caller.
    pub created_by: Option<String>,
    /// `true`: only entries marked as generated by AI; `false`: only the others.
    pub ai_generated: Option<bool>,
    /// Only entries with no translation into this language yet (a BCP 47 code).
    #[param(example = "en")]
    pub missing_locale: Option<String>,
    /// Only entries of this organization unit (store, seller).
    pub owner_org: Option<Uuid>,
    /// Only entries shown on the website of this organization unit: its own and those of the
    /// units above it.
    pub site: Option<Uuid>,
    /// Only entries with at least one of these internal tags (comma-separated ids).
    pub tags_any: Option<String>,
    /// Only entries with every one of these internal tags (comma-separated ids).
    pub tags_all: Option<String>,
}

impl EntriesQuery {
    pub(crate) fn filter(
        self,
        caller: Uuid,
        problems: &mut Vec<autoxide_kernel::error::FieldError>,
    ) -> EntryFilter {
        let created_by = match self.created_by.as_deref().map(str::trim) {
            None | Some("") => None,
            Some("me") => Some(caller),
            Some(raw) => raw.parse::<Uuid>().map_or_else(
                |_| {
                    problems.push(autoxide_kernel::error::FieldError::new(
                        "created_by",
                        "invalid",
                        "must be a user id or `me`",
                    ));
                    None
                },
                Some,
            ),
        };
        let mut tags = |raw: Option<&str>, field: &'static str| -> Vec<Uuid> {
            let mut ids = Vec::new();
            for part in
                raw.unwrap_or_default().split(',').map(str::trim).filter(|part| !part.is_empty())
            {
                match part.parse::<Uuid>() {
                    Ok(id) => ids.push(id),
                    Err(_) => {
                        problems.push(autoxide_kernel::error::FieldError::new(
                            field,
                            "invalid",
                            "must be comma-separated tag ids",
                        ));
                        break;
                    }
                }
            }
            ids
        };
        let tags_any = tags(self.tags_any.as_deref(), "tags_any");
        let tags_all = tags(self.tags_all.as_deref(), "tags_all");
        EntryFilter {
            custom: Vec::new(),
            tags_any,
            tags_all,
            owner_org: self.owner_org,
            site: self.site,
            review_requested: self.review_requested,
            scheduled: self.scheduled,
            created_by,
            ai_generated: self.ai_generated,
            missing_locale: self
                .missing_locale
                .map(|locale| locale.trim().to_owned())
                .filter(|locale| !locale.is_empty()),
            kind: choice(self.kind.as_deref(), "kind", "`post`, `page`, `custom`", problems),
            type_id: self.type_id,
            locale: self
                .locale
                .map(|locale| locale.trim().to_owned())
                .filter(|locale| !locale.is_empty()),
            status: choice(
                self.status.as_deref(),
                "status",
                "`draft`, `published`, `archived`",
                problems,
            ),
            parent: parent_filter(self.parent_id.as_deref(), problems),
            search: self.q,
            term_id: self.term_id,
            author_id: self.author_id,
            translation_group_id: self.translation_group_id,
            sort: choice(self.sort.as_deref(), "sort", "`created_at`, `updated_at`", problems)
                .unwrap_or_default(),
        }
    }
}

/// The editable fields of an entry. Omitted fields stay as they are.
#[derive(Debug, Clone, Default, Deserialize, Validate, ToSchema)]
#[serde(deny_unknown_fields)]
pub(crate) struct EntryFieldsInput {
    /// 1 to 300 characters.
    pub title: Option<String>,
    /// Lower-case letters and digits joined by `-`, at most 100 characters; unique among the
    /// entries of the same kind, language and parent. `""` makes one from the title.
    pub slug: Option<String>,
    /// Up to 1000 characters.
    pub excerpt: Option<String>,
    /// A ProseMirror / Tiptap JSON document (see `BodyNode`); checked by the server. A page may
    /// instead have a block layout (`{"type": "layout", …}`, see `PUT /entries/{id}/layout`).
    #[schema(value_type = Option<BodyNode>)]
    pub body: Option<Value>,
    /// Main image: a media item id; `null` removes it.
    #[serde(default, deserialize_with = "present")]
    #[schema(value_type = Option<Uuid>, nullable)]
    pub featured_media_id: Option<Option<Uuid>>,
    /// Text alternative of the main image, up to 1000 characters.
    pub featured_media_alt: Option<String>,
    /// Title for search engines, up to 300 characters; empty: the title.
    pub meta_title: Option<String>,
    /// Description for search engines, up to 1000 characters.
    pub meta_description: Option<String>,
    /// Image for social sharing: a media item id; `null` removes it.
    #[serde(default, deserialize_with = "present")]
    #[schema(value_type = Option<Uuid>, nullable)]
    pub og_media_id: Option<Option<Uuid>>,
    /// Canonical address, when the content first appeared elsewhere; empty: none.
    pub canonical_url: Option<String>,
    /// Ask search engines not to index it.
    pub noindex: Option<bool>,
    /// The content was generated by AI. AI agents should always send `true`; readers may be
    /// told (public endpoints return it). With only `content.write_own` the server always sets
    /// `true`, whatever is sent.
    pub ai_generated: Option<bool>,
    /// Send `true` when the content was written or edited from AI suggestions (applied
    /// `seo-suggestions`, rewritten from an AI draft); public endpoints return it so the interface
    /// labels it (Vietnam's Law on Artificial Intelligence 134/2025/QH15). Removing the label
    /// (`false` while it is `true`) needs `content.publish` (else 403
    /// `content.ai_label_requires_publish`).
    pub ai_assisted: Option<bool>,
    /// Values of the tenant's custom fields (`GET /api/v1/kernel/custom-fields?target=content.entry`),
    /// by key; `null` clears one. Every problem is listed at once under `custom_fields.<key>`.
    #[schema(value_type = Option<Object>)]
    pub custom_fields: Option<serde_json::Map<String, Value>>,
}

impl From<EntryFieldsInput> for EntryFields {
    fn from(input: EntryFieldsInput) -> Self {
        EntryFields {
            title: input.title,
            slug: input.slug,
            excerpt: input.excerpt,
            body: input.body,
            featured_media_id: input.featured_media_id,
            featured_media_alt: input.featured_media_alt,
            meta_title: input.meta_title,
            meta_description: input.meta_description,
            og_media_id: input.og_media_id,
            canonical_url: input.canonical_url,
            noindex: input.noindex,
            ai_generated: input.ai_generated,
            ai_assisted: input.ai_assisted,
            translated_from: None,
            custom_fields: input.custom_fields,
        }
    }
}

