/// List posts and pages (drafts included).
///
/// Requires `content.read`. Newest first unless `order=asc`. Filter on the tenant's filterable
/// custom fields with `cf.<key>=<eq|in|gte|lte|prefix>:<value>`, e.g. `cf.owner=eq:ada`.
#[utoipa::path(
    get,
    path = "/entries",
    extensions(("x-permissions" = json!(["content.read"]))),
    operation_id = "list_content_entries",
    security(("bearer" = [])),
    params(EntriesQuery, SortChoicePageQuery),
    responses(
        (status = 200, description = "One page of entries.", body = Page<EntryResponse>),
        (status = 401, description = "Not signed in; see `GET /api/v1/auth/me` for the codes.", body = Problem),
        (status = 403, description = "Missing permission `content.read`; code `permission_denied`.", body = Problem),
        (status = 422, description = "A filter or paging parameter is invalid; see `errors`.", body = Problem),
    )
)]
pub(crate) async fn list_entries(
    State(service): State<Arc<ContentService>>,
    tenant: TenantContext,
    principal: Principal,
    Query(query): Query<EntriesQuery>,
    Query(paging): Query<SortChoicePageQuery>,
    Query(raw): Query<std::collections::HashMap<String, String>>,
) -> Result<Page<EntryResponse>, Error> {
    // Kiểm quyền trước khi đọc tham số trang: người không có quyền nhận 403, không phải 422 (D-20261126-list-pages-cluster-2).
    principal.require(&crate::permissions::CONTENT_READ)?;
    let mut problems = Vec::new();
    let mut filter = query.filter(principal.user_id(), &mut problems);
    // Trường tự định nghĩa (bước 51 P19): `cf.<khoá>=<toán tử>:<giá trị>`.
    filter.custom = raw
        .into_iter()
        .filter_map(|(name, value)| name.strip_prefix("cf.").map(|key| (key.to_owned(), value)))
        .collect();
    let page = sorted_page_request(paging, filter.sort.default_order(), problems)?;
    let page = service.list(&tenant, &principal, &filter, &page).await?;
    let autoxide_kernel::pagination::Page { data, pagination } = page;
    Ok(Page { data: describe(&service, &tenant, data).await?, pagination })
}

/// Create a post or page as a draft.
///
/// Requires `content.write` or `content.write_own`. With only `content.write_own`, the parent
/// page must be one you created and the entry is always marked `ai_generated`. An empty or
/// missing `slug` is made from the title (`-2`, `-3`… are added when taken). Retry safely with an
/// `Idempotency-Key` header.
#[utoipa::path(
    post,
    path = "/entries",
    extensions(("x-permissions" = json!(["content.write", "content.write_own"]))),
    operation_id = "create_content_entry",
    security(("bearer" = [])),
    request_body = CreateEntryRequest,
    responses(
        (status = 201, description = "Created.", body = Data<EntryResponse>),
        (status = 401, description = "Not signed in; see `GET /api/v1/auth/me` for the codes.", body = Problem),
        (status = 403, description = "Missing permission `content.write` or `content.write_own` (code `permission_denied`), or the parent page is not yours and you only have `content.write_own` (code `content.not_owner`).", body = Problem),
        (status = 409, description = "The slug is taken; code `content.slug_taken`.", body = Problem),
        (status = 422, description = "A value is invalid: see `errors` (code `content.invalid_body` when only the body is, `content.media_not_found` when only media items are missing).", body = Problem),
    )
)]
pub(crate) async fn create_entry(
    State(service): State<Arc<ContentService>>,
    tenant: TenantContext,
    principal: Principal,
    ValidJson(input): ValidJson<CreateEntryRequest>,
) -> Result<Created<EntryResponse>, Error> {
    let new = NewEntry {
        kind: input.kind,
        type_id: input.type_id,
        locale: input.locale,
        parent_id: input.parent_id,
        org_id: input.org_id,
        fields: input.fields.into(),
    };
    let entry = service.create(&tenant, &principal, new).await?;
    let location = format!("/content/entries/{}", entry.id);
    Ok(Created::new(location, tagged(&service, &tenant, entry).await?.data))
}

/// Get a post or page (its draft).
///
/// Requires `content.read`.
#[utoipa::path(
    get,
    path = "/entries/{id}",
    extensions(("x-permissions" = json!(["content.read"]))),
    operation_id = "get_content_entry",
    security(("bearer" = [])),
    params(("id" = Uuid, Path, description = "Id of the entry.")),
    responses(
        (status = 200, description = "The entry.", body = Data<EntryResponse>, headers(("ETag" = String, description = "Version of the entry: send it back in `If-Match` when changing it."))),
        (status = 401, description = "Not signed in; see `GET /api/v1/auth/me` for the codes.", body = Problem),
        (status = 403, description = "Missing permission `content.read`; code `permission_denied`.", body = Problem),
        (status = 404, description = "No entry has this id; code `content.not_found`.", body = Problem),
    )
)]
pub(crate) async fn get_entry(
    State(service): State<Arc<ContentService>>,
    tenant: TenantContext,
    principal: Principal,
    Path(id): Path<Uuid>,
) -> Result<Tagged<EntryResponse>, Error> {
    tagged(&service, &tenant, service.get(&tenant, &principal, id).await?).await
}

/// Change the draft of a post or page.
///
/// Requires `content.write`, or `content.write_own` for an entry you created. A published entry
/// keeps showing its published version until it
/// is published again (`has_unpublished_changes` turns `true`). `If-Match` is required.
#[utoipa::path(
    patch,
    path = "/entries/{id}",
    extensions(("x-permissions" = json!(["content.write", "content.write_own"]))),
    operation_id = "update_content_entry",
    security(("bearer" = [])),
    params(("id" = Uuid, Path, description = "Id of the entry."), ("If-Match" = String, Header, description = "Required: the `ETag` you read (or `*`). The change is made only if nobody changed the entry since; otherwise `412`.")),
    request_body = UpdateEntryRequest,
    responses(
        (status = 200, description = "The entry after the change.", body = Data<EntryResponse>, headers(("ETag" = String, description = "Version of the entry: send it back in `If-Match` when changing it."))),
        (status = 401, description = "Not signed in; see `GET /api/v1/auth/me` for the codes.", body = Problem),
        (status = 403, description = "Missing permission `content.write` or `content.write_own` (code `permission_denied`), or the entry is not yours and you only have `content.write_own` (code `content.not_owner`).", body = Problem),
        (status = 404, description = "No entry has this id; code `content.not_found`.", body = Problem),
        (status = 409, description = "The slug is taken; code `content.slug_taken`.", body = Problem),
        (status = 412, description = "`If-Match` does not match: the entry changed since you read it; code `precondition_failed`.", body = Problem),
        (status = 422, description = "A value is invalid; see `errors`.", body = Problem),
        (status = 428, description = "`If-Match` is missing; code `precondition_required`.", body = Problem),
    )
)]
pub(crate) async fn update_entry(
    State(service): State<Arc<ContentService>>,
    tenant: TenantContext,
    principal: Principal,
    Path(id): Path<Uuid>,
    if_match: IfMatch,
    ValidJson(input): ValidJson<UpdateEntryRequest>,
) -> Result<Tagged<EntryResponse>, Error> {
    let expected = if_match.required()?;
    let entry = service
        .update(&tenant, &principal, id, input.fields.into(), input.save_revision, expected)
        .await?;
    tagged(&service, &tenant, entry).await
}
