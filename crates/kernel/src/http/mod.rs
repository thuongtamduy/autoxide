//! HTTP server: assembles the modules' routes into one router and wraps around it the layers
//! shared by every request.
//!
//! The routes of module `notes` live under `/api/v1/notes`. The `v1` is the API
//! version: a breaking change opens `/api/v2`, it does not modify `v1`.
//!
//! The OpenAPI document for all routes is at `/api/v1/openapi.json`, for each module at
//! `/api/v1/openapi/<module>.json`; the documentation viewer is at `/api/docs` when enabled by configuration.
//!
//! Every request passes through, from the outside in:
//!
//! 1. **request id** - one ID per request (header `x-request-id`), returned in the
//!    response; if the client sends a valid ID it is used;
//! 2. **log** - one log line per request when done; 5xx errors include the root cause;
//! 3. **CORS** - which browser origins may call;
//! 4. **rate limiting** - each client address may send only so many requests per minute;
//! 5. **idempotency** - a write carrying `Idempotency-Key` that is resent gets the first
//!    result back, and is not done twice;
//! 6. **language** - `Accept-Language` picks the language of the error `detail`;
//! 7. **error normalization** - every error response is Problem Details (RFC 9457), including
//!    errors generated by libraries (404, 405, 413...);
//! 8. **panic catching** - a handler panic becomes a 500 error instead of a dropped connection;
//! 9. **timeout** - a request that runs too long is cut off, returning 503;
//! 10. **body limit** - an oversized body is rejected, returning 413;
//! 11. **304** - a `GET` whose `ETag` matches the client's `If-None-Match` becomes `304 Not Modified`.
//!
//! Outside the log layer (right inside the request id layer) is the **security headers** layer: `nosniff`,
//! `Referrer-Policy`, `X-Frame-Options`, a strict CSP (HSTS when configured) on every response - see
//! `security_headers`.

// URL của gói Scalar đã ghim: trang tài liệu (`DOCS_HTML`) nạp nó và CSP của trang (`DOCS_CSP`) chỉ cho đúng file
// này (L-9 của docs/security/review-2026-11.md). Viết bằng `macro_rules!` thay vì `const` vì `concat!` chỉ ghép chữ
// viết sẵn (literal), không nhận hằng; macro khai trước các `mod` để module con (`security_headers`) dùng được.
macro_rules! scalar_script_url {
    () => {
        "https://cdn.jsdelivr.net/npm/@scalar/api-reference@1.76.4/dist/browser/standalone.js"
    };
}

