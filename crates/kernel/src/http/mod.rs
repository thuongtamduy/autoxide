/// Prefix of every API route.
pub const API_PREFIX: &str = "/api/v1";

/// The fully assembled router, with the OpenAPI documentation of every route in it.
#[non_exhaustive]
pub struct Api {
    pub router: Router,
    pub openapi: OpenApi,
    /// Schema names declared in two places (modules or the kernel) with different content. When merging the
    /// documentation, utoipa keeps one copy and silently drops the other - one side's endpoint would be
    /// described wrongly. Empty means pass; the `autoxide openapi` command (and the test keeping
    /// `docs/openapi.json` in sync with the code) treats this as an error.
    pub schema_conflicts: Vec<String>,
}

/// Assembles the routes of the modules (module name, router) under [`API_PREFIX`], adds the
/// `root` routes at the root (outside `/api/v1`, e.g. [`health_routes`]), and wraps the shared layers
/// around all of them.
///
/// Things shared by every request, besides routes. Build with `Extras::default()` then the
/// functions that set each field.
#[derive(Clone, Default)]
#[non_exhaustive]
pub struct Extras {
    /// The authenticator a module has published; handlers taking
    /// [`Principal`](crate::access::Principal) use it. `None`: no module provides
    /// authentication yet - a handler that needs login returns a 500 error stating what is missing.
    pub authenticator: Option<Arc<dyn Authenticator>>,
    /// Where idempotency keys are stored (provided by a module). `None`: the
    /// `Idempotency-Key` header is ignored.
    pub idempotency: Option<Arc<dyn IdempotencyStore>>,
    /// Deprecated endpoints declared by modules: `(module name, declaration)`.
    pub deprecations: Vec<(&'static str, Deprecation)>,
    /// Names of experimental-tier modules: every one of their operations carries `x-stability` (step 70 P3).
    pub experimental: Vec<&'static str>,
    /// Request body limits specific to routes declared by modules: `(module name, declaration)`.
    pub body_limits: Vec<(&'static str, BodyLimit)>,
    /// MCP tools of the modules, full names (`Modules::tools`). The `/mcp` endpoint is present
    /// when there is an `authenticator`.
    pub tools: Vec<crate::mcp::Tool>,
    /// MCP resources of the modules, full URIs (`Modules::mcp_resources`). The kernel adds
    /// `autoxide://kernel/llms.txt` and `autoxide://kernel/openapi.json`.
    pub resources: Vec<crate::mcp::McpResource>,
    /// MCP prompts of the modules, full names (`Modules::prompts`).
    pub prompts: Vec<crate::mcp::Prompt>,
    /// Names and descriptions of the modules (`Modules::descriptions`), for `/llms.txt`.
    pub modules: Vec<(&'static str, &'static str)>,
    /// Public URL of the API (`AUTOXIDE_HTTP_PUBLIC_URL`): `/llms.txt` links are absolute when set.
    pub public_url: Option<String>,
    /// The OAuth authorization server a module published (step 71 G4): with `public_url` set, the kernel serves
    /// the discovery documents and accepts OAuth access tokens issued for this server's resources.
    pub authorization_server: Option<Arc<dyn crate::access::AuthorizationServer>>,
    /// Error message translations (default: to use only the kernel's translations use
    /// `Translations::new(Vec::new())`; empty means every error is in English).
    pub translations: Translations,
    /// The installation's database registry (step 33): handlers taking
    /// [`TenantContext`](crate::tenancy::TenantContext) use it. `None`: a handler that needs a tenant returns a
    /// 500 error stating what is missing.
    pub tenancy: Option<crate::tenancy::DatabaseRegistry>,
    /// Per-tenant entitlements (step 35): routes and MCP tools of modules that the tenant's plan lacks are
    /// blocked. Default: no provider, nothing blocked.
    pub entitlements: crate::entitlement::EntitlementsHandle,
    /// Syncable record kinds of the modules (`Modules::sync_resources`, step 69 P2): when present the
    /// kernel serves `/api/v1/kernel/sync/...` (a write batch runs commands through these modules' routes).
    pub sync: Vec<(&'static str, crate::sync::SyncResource)>,
    // Chỉ bật được qua `without_permission_gate` (feature `permission-audit`, testkit); riêng tư để không ai đặt thẳng.
    without_permission_gate: bool,
}

